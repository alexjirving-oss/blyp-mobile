/*
  Generates src/aws-exports.js from environment variables for EAS builds and local runs.
  This avoids bundling failures when aws-exports.js is .gitignored.

  Expected env vars (set in EAS Project → Environment Variables):
    - EXPO_PUBLIC_AWS_REGION (or EXPO_PUBLIC_AMPLIFY_REGION)
    - EXPO_PUBLIC_AWS_USER_POOL_ID (or EXPO_PUBLIC_AMPLIFY_USER_POOL_ID)
    - EXPO_PUBLIC_AWS_USER_POOL_WEB_CLIENT_ID (or EXPO_PUBLIC_AMPLIFY_USER_POOL_WEB_CLIENT_ID)
    - Optional: EXPO_PUBLIC_AWS_IDENTITY_POOL_ID (or EXPO_PUBLIC_AMPLIFY_IDENTITY_POOL_ID)

  All are public identifiers; no secrets.
*/

const fs = require('fs');
const path = require('path');

function pickEnv(...keys) {
  for (const k of keys) {
    if (process.env[k] && String(process.env[k]).trim()) return String(process.env[k]).trim();
  }
  return '';
}

const LOCKED_USER_POOL_WEB_CLIENT_ID = '4a7r115hllaedriqsjlsa00snj';
const LOCKED_USER_POOL_ID = 'eu-west-2_ITX07Zvnt';
const cognitoDomain = pickEnv('EXPO_PUBLIC_COGNITO_DOMAIN');
const redirectSignIn = pickEnv('EXPO_PUBLIC_COGNITO_REDIRECT_SIGN_IN') || 'blyp://auth/';
const redirectSignOut = pickEnv('EXPO_PUBLIC_COGNITO_REDIRECT_SIGN_OUT') || 'blyp://auth/signout/';
const socialProviders = (pickEnv('EXPO_PUBLIC_SOCIAL_PROVIDERS') || 'Google,Facebook')
  .split(',')
  .map((provider) => provider.trim())
  .filter(Boolean);

const config = {
  aws_project_region: pickEnv('EXPO_PUBLIC_AWS_REGION', 'EXPO_PUBLIC_AMPLIFY_REGION', 'AWS_REGION', 'AMPLIFY_REGION') || 'eu-west-2',
  aws_cognito_region: pickEnv('EXPO_PUBLIC_AWS_COGNITO_REGION', 'EXPO_PUBLIC_AWS_REGION', 'EXPO_PUBLIC_AMPLIFY_REGION', 'AWS_REGION') || 'eu-west-2',
  aws_user_pools_id: pickEnv('EXPO_PUBLIC_AWS_USER_POOL_ID', 'EXPO_PUBLIC_AMPLIFY_USER_POOL_ID') || LOCKED_USER_POOL_ID,
  aws_user_pools_web_client_id: LOCKED_USER_POOL_WEB_CLIENT_ID,
  aws_cognito_identity_pool_id: pickEnv('EXPO_PUBLIC_AWS_IDENTITY_POOL_ID', 'EXPO_PUBLIC_AMPLIFY_IDENTITY_POOL_ID'),
  aws_cognito_social_providers: cognitoDomain ? socialProviders : [],
  oauth: cognitoDomain
    ? {
        domain: cognitoDomain.replace(/^https?:\/\//, '').replace(/\/+$/, ''),
        scope: ['openid', 'email', 'profile'],
        redirectSignIn,
        redirectSignOut,
        responseType: 'code',
      }
    : {}
};

const envClient = pickEnv('EXPO_PUBLIC_AWS_USER_POOL_WEB_CLIENT_ID', 'EXPO_PUBLIC_AMPLIFY_USER_POOL_WEB_CLIENT_ID', 'EXPO_PUBLIC_USER_POOL_WEB_CLIENT_ID');
if (envClient && envClient !== LOCKED_USER_POOL_WEB_CLIENT_ID) {
  console.warn(`[aws-exports] Ignoring mismatched client ${envClient}; using locked ${LOCKED_USER_POOL_WEB_CLIENT_ID}`);
}

const required = {
  aws_user_pools_id: 'EXPO_PUBLIC_AWS_USER_POOL_ID / EXPO_PUBLIC_AMPLIFY_USER_POOL_ID',
  aws_user_pools_web_client_id: 'EXPO_PUBLIC_AWS_USER_POOL_WEB_CLIENT_ID / EXPO_PUBLIC_AMPLIFY_USER_POOL_WEB_CLIENT_ID',
  aws_project_region: 'EXPO_PUBLIC_AWS_REGION / EXPO_PUBLIC_AMPLIFY_REGION',
  aws_cognito_region: 'EXPO_PUBLIC_AWS_COGNITO_REGION or same as region'
};

const missing = Object.entries(required)
  .filter(([k]) => !config[k] || !String(config[k]).trim())
  .map(([, hint]) => hint);

if (missing.length) {
  console.warn('[aws-exports] Missing env values. Set these in EAS → Environment variables:');
  for (const m of missing) console.warn(' -', m);
}

const dst = path.join(process.cwd(), 'src', 'aws-exports.js');
const js = `// Auto-generated by scripts/generate-aws-exports.js\n// Do not edit by hand. Values come from EXPO_PUBLIC_* env vars.\nexport default ${JSON.stringify(config, null, 2)};\n`;

const exists = fs.existsSync(dst);
if (true) {
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, js, 'utf8');
  console.log('[aws-exports] Wrote', dst);
} else {
  console.log('[aws-exports] Skipped writing; file already exists:', dst);
}
